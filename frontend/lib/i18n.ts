export const MESSAGES: Record<Language, Record<MessageKey, string>> = { tr, en };

export function translate(language: Language, key: MessageKey, variables: Record<string, string | number> = {}): string {
  const template = MESSAGES[language][key] ?? MESSAGES[DEFAULT_LANGUAGE][key] ?? key;
  return template.replace(/\{(\w+)\}/g, (match, name: string) => (name in variables ? String(variables[name]) : match));
}
